-- 月度盘点记录：每个已结束月份保留一份月末系统库存快照。
-- 实际盘点完成后，按“实际 - 月末系统/上次已应用盘点值”的差额修正当前库存，
-- 这样即使盘点结果在下个月才录入，也不会把今天库存直接覆盖成上个月的数量。

create table if not exists public.monthly_stocktake_records (
  id bigint generated by default as identity primary key,
  month_key text not null check (month_key ~ '^[0-9]{4}-[0-9]{2}$'),
  cutoff_date date not null,
  item_id uuid not null,
  item_name text not null,
  category text,
  spec text,
  unit text,
  system_fridge numeric not null default 0,
  system_warehouse numeric not null default 0,
  applied_fridge numeric not null default 0,
  applied_warehouse numeric not null default 0,
  actual_fridge numeric,
  actual_warehouse numeric,
  note text,
  checked_at timestamptz,
  checked_by text,
  created_at timestamptz not null default now(),
  created_by text,
  unique(month_key,item_id)
);

alter table public.monthly_stocktake_records enable row level security;

drop policy if exists monthly_stocktake_records_select on public.monthly_stocktake_records;
create policy monthly_stocktake_records_select
on public.monthly_stocktake_records
for select
to authenticated
using (public.is_app_active());

drop policy if exists monthly_stocktake_records_insert on public.monthly_stocktake_records;
create policy monthly_stocktake_records_insert
on public.monthly_stocktake_records
for insert
to authenticated
with check (public.is_app_active());

drop policy if exists monthly_stocktake_records_update on public.monthly_stocktake_records;
create policy monthly_stocktake_records_update
on public.monthly_stocktake_records
for update
to authenticated
using (public.is_app_active())
with check (public.is_app_active());

grant select, insert, update on public.monthly_stocktake_records to authenticated;
grant usage, select on sequence public.monthly_stocktake_records_id_seq to authenticated;

create or replace function public.save_monthly_stocktake_result(
  p_month_key text,
  p_item uuid,
  p_actual_fridge numeric,
  p_actual_warehouse numeric,
  p_note text default ''
)
returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  r public.monthly_stocktake_records%rowtype;
  i public.inventory_items%rowtype;
  month_start date;
  delta_f numeric;
  delta_w numeric;
  next_f numeric;
  next_w numeric;
  before_f numeric;
  before_w numeric;
  email text := coalesce(auth.jwt()->>'email','');
  note_text text := trim(coalesce(p_note,''));
  month_text text;
  is_restored boolean;
begin
  if not public.is_app_active() then raise exception '此账号已停用'; end if;
  if p_month_key is null or p_month_key !~ '^[0-9]{4}-[0-9]{2}$' then raise exception '盘点月份不正确'; end if;
  month_start := to_date(p_month_key || '-01','YYYY-MM-DD');
  if to_char(month_start,'YYYY-MM') <> p_month_key then raise exception '盘点月份不正确'; end if;
  if month_start >= date_trunc('month',current_date)::date then raise exception '本月尚未结束，不能进行月底盘点调整'; end if;
  if p_actual_fridge is null or p_actual_fridge < 0 then raise exception '实际冰箱库存不能小于 0'; end if;
  if p_actual_warehouse is null or p_actual_warehouse < 0 then raise exception '实际仓库库存不能小于 0'; end if;

  select * into r
  from public.monthly_stocktake_records
  where month_key=p_month_key and item_id=p_item
  for update;
  if not found then raise exception '找不到该月份的盘点记录，请先刷新盘点页面'; end if;

  select * into i
  from public.inventory_items
  where id=p_item
  for update;
  if not found then raise exception '找不到饮料'; end if;

  before_f := coalesce(r.applied_fridge,r.system_fridge,0);
  before_w := coalesce(r.applied_warehouse,r.system_warehouse,0);
  delta_f := p_actual_fridge - before_f;
  delta_w := p_actual_warehouse - before_w;

  next_f := coalesce(i.fridge_quantity,0) + delta_f;
  next_w := coalesce(i.warehouse_quantity,0) + delta_w;
  if next_f < 0 then raise exception '调整后当前冰箱库存会小于 0，请先核对后续库存记录'; end if;
  if next_w < 0 then raise exception '调整后当前仓库库存会小于 0，请先核对后续库存记录'; end if;

  update public.inventory_items
  set fridge_quantity=next_f,
      warehouse_quantity=next_w,
      quantity=next_f+next_w,
      updated_at=now()
  where id=i.id;

  month_text := extract(year from r.cutoff_date)::int || '年' || extract(month from r.cutoff_date)::int || '月月底盘点';
  is_restored := p_actual_fridge = r.system_fridge and p_actual_warehouse = r.system_warehouse;

  -- 月度盘点明细只保留“目前有效的最终调整”。
  -- 用户如果后来发现之前盘错了并改回系统月末数量，旧调整记录会一起清掉。
  delete from public.inventory_logs
  where item_id=i.id
    and action='ADJUST'
    and operation_date=r.cutoff_date
    and note like '%｜' || month_text || '%';

  if is_restored then
    update public.monthly_stocktake_records
    set actual_fridge=null,
        actual_warehouse=null,
        applied_fridge=r.system_fridge,
        applied_warehouse=r.system_warehouse,
        note=null,
        checked_at=null,
        checked_by=null
    where id=r.id;

    return jsonb_build_object(
      'ok',true,
      'cleared',true,
      'month_key',p_month_key,
      'item_id',p_item,
      'delta_fridge',delta_f,
      'delta_warehouse',delta_w,
      'current_fridge',next_f,
      'current_warehouse',next_w
    );
  end if;

  -- 重新写成“月末系统数量 → 最终确认数量”，避免历史中留下反复修改的多笔记录。
  if p_actual_fridge <> r.system_fridge then
    insert into public.inventory_logs(item_id,item_name,action,quantity,note,user_email,operation_date,out_type)
    values(
      i.id,i.name,'ADJUST',p_actual_fridge,
      '冰箱｜盘点调整｜调整前 '||r.system_fridge||'｜调整后 '||p_actual_fridge||'｜'||month_text||
        case when note_text<>'' then '｜'||note_text else '' end,
      email,r.cutoff_date,null
    );
  end if;

  if p_actual_warehouse <> r.system_warehouse then
    insert into public.inventory_logs(item_id,item_name,action,quantity,note,user_email,operation_date,out_type)
    values(
      i.id,i.name,'ADJUST',p_actual_warehouse,
      '仓库｜盘点调整｜调整前 '||r.system_warehouse||'｜调整后 '||p_actual_warehouse||'｜'||month_text||
        case when note_text<>'' then '｜'||note_text else '' end,
      email,r.cutoff_date,null
    );
  end if;

  update public.monthly_stocktake_records
  set actual_fridge=p_actual_fridge,
      actual_warehouse=p_actual_warehouse,
      applied_fridge=p_actual_fridge,
      applied_warehouse=p_actual_warehouse,
      note=note_text,
      checked_at=now(),
      checked_by=email
  where id=r.id;

  return jsonb_build_object(
    'ok',true,
    'cleared',false,
    'month_key',p_month_key,
    'item_id',p_item,
    'system_fridge',r.system_fridge,
    'system_warehouse',r.system_warehouse,
    'previous_applied_fridge',before_f,
    'previous_applied_warehouse',before_w,
    'actual_fridge',p_actual_fridge,
    'actual_warehouse',p_actual_warehouse,
    'delta_fridge',delta_f,
    'delta_warehouse',delta_w,
    'current_fridge',next_f,
    'current_warehouse',next_w
  );
end;
$function$;

grant execute on function public.save_monthly_stocktake_result(text,uuid,numeric,numeric,text) to authenticated;
