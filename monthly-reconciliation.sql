-- 月结核对 / POS 月销量
-- 1) 出库类型：正常销售、签单、FOC、厨房、员工、招待、其他
alter table public.inventory_logs
  add column if not exists out_type text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname='inventory_logs_out_type_check'
      and conrelid='public.inventory_logs'::regclass
  ) then
    alter table public.inventory_logs
      add constraint inventory_logs_out_type_check
      check (out_type is null or out_type in ('NORMAL','CREDIT','FOC','KITCHEN','STAFF','ENT','OTHER'));
  end if;
end $$;

-- 2) 每月 POS 销量，仅用于对账，不修改库存。
create table if not exists public.monthly_pos_sales (
  id bigint generated by default as identity primary key,
  month_key text not null,
  item_id uuid not null references public.inventory_items(id) on delete cascade,
  item_name text not null,
  pos_quantity numeric not null default 0 check (pos_quantity >= 0),
  updated_by text not null default '',
  updated_at timestamptz not null default now(),
  unique(month_key,item_id),
  constraint monthly_pos_sales_month_key_check check (month_key ~ '^[0-9]{4}-[0-9]{2}$')
);

alter table public.monthly_pos_sales enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='monthly_pos_sales' and policyname='active users can read monthly pos sales') then
    create policy "active users can read monthly pos sales" on public.monthly_pos_sales for select to authenticated using (is_app_active());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='monthly_pos_sales' and policyname='active users can insert monthly pos sales') then
    create policy "active users can insert monthly pos sales" on public.monthly_pos_sales for insert to authenticated with check (is_app_active());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='monthly_pos_sales' and policyname='active users can update monthly pos sales') then
    create policy "active users can update monthly pos sales" on public.monthly_pos_sales for update to authenticated using (is_app_active()) with check (is_app_active());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='monthly_pos_sales' and policyname='active users can delete monthly pos sales') then
    create policy "active users can delete monthly pos sales" on public.monthly_pos_sales for delete to authenticated using (is_app_active());
  end if;
end $$;

grant select,insert,update,delete on public.monthly_pos_sales to authenticated;
grant usage,select on sequence public.monthly_pos_sales_id_seq to authenticated;

-- 4) 月结核对人工备注 / 人工确认。
-- 自动“状态”仍保留系统计算结果；人工确认只表示该差异已人工核实并有合理原因。
create table if not exists public.monthly_reconciliation_review (
  id bigint generated by default as identity primary key,
  month_key text not null,
  item_id uuid not null references public.inventory_items(id) on delete cascade,
  item_name text not null,
  note text not null default '',
  manual_ok boolean not null default false,
  updated_by text not null default '',
  updated_at timestamptz not null default now(),
  unique(month_key,item_id),
  constraint monthly_reconciliation_review_month_key_check check (month_key ~ '^[0-9]{4}-[0-9]{2}$')
);

alter table public.monthly_reconciliation_review enable row level security;

drop policy if exists monthly_reconciliation_review_select on public.monthly_reconciliation_review;
create policy monthly_reconciliation_review_select
on public.monthly_reconciliation_review
for select to authenticated
using (public.is_app_active());

drop policy if exists monthly_reconciliation_review_insert on public.monthly_reconciliation_review;
create policy monthly_reconciliation_review_insert
on public.monthly_reconciliation_review
for insert to authenticated
with check (public.is_app_active());

drop policy if exists monthly_reconciliation_review_update on public.monthly_reconciliation_review;
create policy monthly_reconciliation_review_update
on public.monthly_reconciliation_review
for update to authenticated
using (public.is_app_active())
with check (public.is_app_active());

drop policy if exists monthly_reconciliation_review_delete on public.monthly_reconciliation_review;
create policy monthly_reconciliation_review_delete
on public.monthly_reconciliation_review
for delete to authenticated
using (public.is_app_active());

grant select,insert,update,delete on public.monthly_reconciliation_review to authenticated;
grant usage,select on sequence public.monthly_reconciliation_review_id_seq to authenticated;


-- 5) 人工确认必须绑定“当时的对账差异 + 当时的核对基础”。
-- POS / 库存 / 特殊用途 / 备注任一变化后，旧的人工 OK 会自动失效，必须重新确认。
alter table public.monthly_reconciliation_review
  add column if not exists confirmed_diff numeric,
  add column if not exists confirmed_signature text,
  add column if not exists confirmed_at timestamptz,
  add column if not exists confirmed_by text not null default '';

-- 升级前的人工 OK 没有保存确认基准，不能继续当成有效确认。
update public.monthly_reconciliation_review
set manual_ok=false,
    confirmed_diff=null,
    confirmed_signature=null,
    confirmed_at=null,
    confirmed_by=''
where manual_ok=true
  and (confirmed_signature is null or confirmed_diff is null);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname='monthly_reconciliation_review_manual_ok_note_check'
      and conrelid='public.monthly_reconciliation_review'::regclass
  ) then
    alter table public.monthly_reconciliation_review
      add constraint monthly_reconciliation_review_manual_ok_note_check
      check (not manual_ok or btrim(note) <> '');
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname='monthly_reconciliation_review_manual_ok_basis_check'
      and conrelid='public.monthly_reconciliation_review'::regclass
  ) then
    alter table public.monthly_reconciliation_review
      add constraint monthly_reconciliation_review_manual_ok_basis_check
      check (
        not manual_ok
        or (confirmed_diff is not null and confirmed_signature is not null and confirmed_at is not null)
      );
  end if;
end $$;
